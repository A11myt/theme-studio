const HOME = "C:\\Users\\jason";
const ENV: WinEnv = {
  os: "windows", home: HOME, appdata: `${HOME}\\AppData\\Roaming`, localappdata: `${HOME}\\AppData\\Local`,
  documents: `${HOME}\\OneDrive - Firma GmbH\\Dokumente`, komorebiConfigHome: "", logFile: "log",
  windowsBuild: "Windows 11 Pro 24H2 (Build 26100)",
  tools: { komorebic: `${HOME}\\scoop\\shims\\komorebic.exe`, "oh-my-posh": `${HOME}\\scoop\\shims\\oh-my-posh.exe`, pwsh: "C:\\pwsh.exe" },
};
const WT = `${ENV.localappdata}\\Packages\\Microsoft.WindowsTerminal_8wekyb3d8bbwe\\LocalState\\settings.json`;
const VS_DIR = `${ENV.appdata}\\Code\\User`;
const VS = `${VS_DIR}\\settings.json`;
const PS5 = `${ENV.documents}\\WindowsPowerShell\\Microsoft.PowerShell_profile.ps1`;
const PS7 = `${ENV.documents}\\PowerShell\\Microsoft.PowerShell_profile.ps1`;
const KOMO = `${HOME}\\komorebi.json`;
const KBAR = `${HOME}\\komorebi.bar.json`;

function fakeWindows(files: Record<string, string>, opts: { env?: Partial<WinEnv>; fonts?: string[]; komorebi?: { state: number; reload: number; output?: string }; policy?: Partial<Record<"powershell" | "pwsh", string>> } = {}) {
  const fs = new Map(Object.entries(files));
  const dirs = new Set<string>();
  for (const f of fs.keys()) dirs.add(f.slice(0, f.lastIndexOf("\\")));
  const reg: RegSet[] = [];
  const log: string[] = [];
  const calls: string[] = [];
  const b: Bridge = {
    env: async () => ({ ...ENV, ...opts.env }),
    exists: async (p) => fs.has(p) || dirs.has(p),
    read: async (p) => fs.get(p) ?? null,
    backupBegin: async () => "1700000000000",
    write: async (_s, p, text, bom) => { fs.set(p, (bom ? "\uFEFF" : "") + text); },
    regApply: async (_s, v) => { reg.push(...v); },
    setWallpaper: async (p) => { calls.push(`wallpaper ${p}`); },
    broadcastColors: async () => { calls.push("broadcast"); },
    runTool: async (tool, args) => {
      calls.push(`${tool} ${args.join(" ")}`);
      const k = opts.komorebi ?? { state: 0, reload: 0 };
      return args[0] === "state" ? { code: k.state, output: "" } : { code: k.reload, output: k.output ?? "" };
    },
    psPolicy: async () => opts.policy ?? {},
    fonts: async () => opts.fonts ?? ["Iosevka Nerd Font Mono", "Hack Nerd Font Mono"],
    log: async (lines) => { log.push(...lines); return "apply.log"; },
    logTail: async () => log.slice(-20).join("\n"),
    backups: async () => [],
    restore: async () => [],
  };
  return { b, fs, reg, log, calls, dirs };
}

const OPTS: ApplyOptions = {
  name: "Dusk", settings: { source: "#944365", scheme: "tonal-spot", mode: "dark", contrast: 0 },
  fonts: FONT_PRESETS.iosevka, prompt: DEFAULT_PROMPT, imagePath: `${HOME}\\Pictures\\Wallpapers\\dusk.jpg`, titlebars: false, withFonts: true,
};

// typische echte Dateien: Kommentare, Komma am Ende, eigene Einträge
const WT_TEXT = `// This file was initially generated by Windows Terminal
{
    "$schema": "https://aka.ms/terminal-profiles-schema",
    "defaultProfile": "{61c54bbd}",
    "profiles": { "defaults": { "elevate": true }, "list": [ { "name": "PowerShell", "guid": "{61c54bbd}" }, ] },
    "schemes": [ { "name": "Campbell", "background": "#0C0C0C" } ], // eigenes Schema bleibt
}`;
const VS_TEXT = `{
    // meine Einstellungen
    "editor.minimap.enabled": false,
    "workbench.colorTheme": "Default Dark Modern" // Kommentar am Ende ohne Komma
}`;
const PS_TEXT = `. 'C:\\Users\\jason\\dotfiles-windows\\.config\\powershell\\Microsoft.PowerShell_profile.ps1'\r\noh-my-posh init pwsh --config 'alt.json' | Invoke-Expression\r\n`;

describe("JSONC", () => {
  it("Kommentare, Kommas, Strings mit // bleiben richtig", () => {
    expect(parseJsonc('{ "url": "https://x.y//z", /* a */ "a": [1,], // b\n }')).toEqual({ url: "https://x.y//z", a: [1] });
  });
  it("Block wird angehängt, ersetzt und bleibt gültig – auch nach Kommentar ohne Komma", () => {
    const once = upsertBlock(VS_TEXT, "  // >>> x", "  // <<< x", { a: 1 });
    expect(parseJsonc(once)).toMatchObject({ "editor.minimap.enabled": false, a: 1 });
    expect(once).toContain("// Kommentar am Ende ohne Komma");
    const twice = upsertBlock(once, "  // >>> x", "  // <<< x", { a: 2 });
    expect(parseJsonc(twice)).toMatchObject({ a: 2 });
    expect(twice.match(/>>> x/g)).toHaveLength(1);
  });
  it("leere Datei / nur {} funktioniert", () => {
    expect(parseJsonc(upsertBlock("{}", ">>>", "<<<", { a: 1 }).replace(/>>>|<<</g, ""))).toEqual({ a: 1 });
    expect(parseJsonc(upsertBlock("", "  // >>>", "  // <<<", { a: 1 }))).toEqual({ a: 1 });
  });
  it("Fehlermeldung nennt die Zeile", () => {
    expect(() => parseJsonc('{\n "a": 1\n "b": 2\n}')).toThrow(/Zeile 3/);
    expect(stripJsonc('"a//b"')).toBe('"a//b"');
  });
});

describe("Windows anwenden (alles installiert)", () => {
  it("setzt alle Ziele, lässt Fremdes stehen, Protokoll + Registry stimmen", async () => {
    const w = fakeWindows({ [WT]: WT_TEXT, [VS]: VS_TEXT, [PS5]: PS_TEXT, [KOMO]: '{ "border": true }', [KBAR]: '{ "height": 34 }' });
    const { results } = await applyAll(w.b, OPTS);
    expect(Object.fromEntries(results.map((r) => [r.id, r.status]))).toEqual({ windows: "ok", terminal: "ok", vscode: "ok", ohmyposh: "ok", komorebi: "ok" });
    // Windows Terminal: eigenes Schema + Profil bleiben, unseres dazu
    const wt = JSON.parse(w.fs.get(WT)!);
    expect(wt.schemes.map((s: any) => s.name)).toEqual(["Campbell", "Theme Studio"]);
    expect(wt.profiles.defaults).toMatchObject({ elevate: true, colorScheme: "Theme Studio", font: { face: "Iosevka Nerd Font Mono" } });
    expect(wt.profiles.list[0].name).toBe("PowerShell");
    // VS Code: Kommentare und eigene Einträge bleiben
    const vs = w.fs.get(VS)!;
    expect(vs).toContain("// meine Einstellungen");
    expect(parseJsonc(vs)["editor.minimap.enabled"]).toBe(false);
    expect((parseJsonc(vs)["workbench.colorCustomizations"] as any)["editor.background"]).toBe(palette(OPTS.settings).surface);
    // PowerShell: beide Profile (7 neu angelegt, OneDrive-Dokumente), mit BOM, Block am Ende, Altes bleibt
    for (const p of [PS5, PS7]) {
      const t = w.fs.get(p)!;
      expect(t.startsWith("\uFEFF")).toBe(true);
      expect(t.trimEnd().endsWith("# <<< theme-studio")).toBe(true);
    }
    expect(w.fs.get(PS5)).toContain("dotfiles-windows");
    expect(w.fs.get(`${HOME}\\.config\\theme-studio\\prompt.omp.json`)).toContain(palette(OPTS.settings).primary);
    // komorebi: Theme gesetzt, eigene Werte bleiben, neu geladen
    expect(JSON.parse(w.fs.get(KOMO)!)).toMatchObject({ border: true, theme: { palette: "Custom" } });
    expect(JSON.parse(w.fs.get(KBAR)!)).toMatchObject({ height: 34, theme: { accent: "Base0D" } });
    expect(w.calls).toEqual([`wallpaper ${OPTS.imagePath}`, "broadcast", "komorebic state", "komorebic reload-configuration"]);
    // Registry: 10 Werte, Akzentpalette 8×4 Bytes, dunkel
    expect(w.reg).toHaveLength(10);
    expect((w.reg.find((r) => r.name === "AccentPalette")!.value as any).value).toHaveLength(32);
    expect(w.reg.find((r) => r.name === "AppsUseLightTheme")!.value).toEqual({ kind: "Dword", value: 0 });
    expect(w.log.join("\n")).toMatch(/\[OK {5}\] Windows Terminal/);
  });

  it("zweimal anwenden → keine doppelten Blöcke/Schemata", async () => {
    const w = fakeWindows({ [WT]: WT_TEXT, [VS]: VS_TEXT, [PS5]: PS_TEXT, [KOMO]: "{}" });
    await applyAll(w.b, OPTS);
    await applyAll(w.b, { ...OPTS, settings: { ...OPTS.settings, scheme: "vibrant" } });
    expect(JSON.parse(w.fs.get(WT)!).schemes.filter((s: any) => s.name === "Theme Studio")).toHaveLength(1);
    expect(w.fs.get(VS)!.match(/>>> theme-studio/g)).toHaveLength(1);
    expect(w.fs.get(PS5)!.match(/>>> theme-studio/g)).toHaveLength(1);
  });
});

describe("Fallstricke", () => {
  it("nichts installiert → übersprungen mit Hinweis, nichts geschrieben", async () => {
    const w = fakeWindows({}, { env: { tools: {} } });
    const { results } = await applyAll(w.b, { ...OPTS, imagePath: undefined });
    const by = Object.fromEntries(results.map((r) => [r.id, r]));
    expect(by.windows.status).toBe("ok");                       // Registry geht immer
    for (const id of ["terminal", "vscode", "ohmyposh", "komorebi"]) expect(by[id].status).toBe("skipped");
    expect(by.terminal.message).toMatch(/einmal öffnen/);
    expect(by.ohmyposh.message).toMatch(/winget install JanDeDobbeleer.OhMyPosh/);
    expect(by.komorebi.message).toMatch(/scoop install komorebi/);
    expect(w.fs.size).toBe(0);
  });
  it("komorebi installiert, aber keine komorebi.json → eigener Hinweis", async () => {
    const w = fakeWindows({});
    const { results } = await applyAll(w.b, { ...OPTS, only: ["komorebi"] });
    expect(results[0]).toMatchObject({ status: "skipped" });
    expect(results[0].message).toMatch(/komorebi.json nicht gefunden in C:\\Users\\jason/);
  });
  it("kaputte VS-Code-Datei → Fehler mit Zeile, Datei unverändert, Rest läuft weiter", async () => {
    const broken = '{\n  "a": 1\n  "b": 2\n}';
    const w = fakeWindows({ [VS]: broken, [WT]: WT_TEXT });
    const { results } = await applyAll(w.b, OPTS);
    const vs = results.find((r) => r.id === "vscode")!;
    expect(vs.status).toBe("error");
    expect(vs.message).toMatch(/Zeile 3/);
    expect(w.fs.get(VS)).toBe(broken);
    expect(results.find((r) => r.id === "terminal")!.status).toBe("ok");
  });
  it("Schrift nicht installiert → Warnung, Farben trotzdem", async () => {
    const w = fakeWindows({ [WT]: WT_TEXT }, { fonts: ["Consolas"] });
    const { results } = await applyAll(w.b, { ...OPTS, only: ["terminal"] });
    expect(results[0].status).toBe("warn");
    expect(results[0].message).toMatch(/Nerd Fonts installieren/);
    expect(JSON.parse(w.fs.get(WT)!).profiles.defaults.font).toBeUndefined();
  });
  it("komorebi lehnt Konfiguration ab → Fehler mit seiner Meldung", async () => {
    const w = fakeWindows({ [KOMO]: "{}" }, { komorebi: { state: 0, reload: 1, output: "Error: unknown variant `Custom`" } });
    const { results } = await applyAll(w.b, { ...OPTS, only: ["komorebi"] });
    expect(results[0]).toMatchObject({ status: "error" });
    expect(results[0].message).toMatch(/unknown variant/);
  });
  it("komorebi läuft nicht → gespeichert, kein Neuladen", async () => {
    const w = fakeWindows({ [KOMO]: "{}" }, { komorebi: { state: 1, reload: 0 } });
    const { results } = await applyAll(w.b, { ...OPTS, only: ["komorebi"] });
    expect(results[0].message).toMatch(/nächsten Start/);
    expect(w.calls).not.toContain("komorebic reload-configuration");
  });
  it("KOMOREBI_CONFIG_HOME wird beachtet", async () => {
    const dir = `${HOME}\\.config\\komorebi`;
    const w = fakeWindows({ [`${dir}\\komorebi.json`]: "{}" }, { env: { komorebiConfigHome: dir } });
    const { results } = await applyAll(w.b, { ...OPTS, only: ["komorebi"] });
    expect(results[0].status).toBe("ok");
  });
  it("PowerShell 7 nicht installiert und kein Profil → nur 5.1", async () => {
    const w = fakeWindows({}, { env: { tools: { "oh-my-posh": "x" } } });
    const { results } = await applyAll(w.b, { ...OPTS, only: ["ohmyposh"] });
    expect(results[0].message).toMatch(/Windows PowerShell 5\.1 –/);
    expect(w.fs.has(PS7)).toBe(false);
  });
  it("Pfad mit Apostroph im Profil richtig maskiert", () => {
    const t = upsertProfile(null, `# >>> theme-studio (wird beim Anwenden ersetzt)\r\n--config 'C:\\Users\\O''Brien'\r\n# <<< theme-studio`);
    expect(t).toContain("O''Brien");
    expect(upsertProfile(t, null).trim()).toBe("");
  });
  it("hell + Titelleisten", () => {
    const r = registryValues({ ...OPTS.settings, mode: "light" }, true);
    expect(r.find((x) => x.name === "SystemUsesLightTheme")!.value).toEqual({ kind: "Dword", value: 1 });
    expect(r.find((x) => x.name === "ColorPrevalence")!.value).toEqual({ kind: "Dword", value: 1 });
    expect(accentPalette(OPTS.settings)).toHaveLength(8);
  });
  it("VS Code ohne settings.json → wird angelegt", () => {
    const out = mergeVscode(null, palette(OPTS.settings), OPTS);
    expect(Object.keys(parseJsonc(out))).toContain("editor.fontFamily");
  });
  it("altes wintheme wird erkannt und gemeldet", async () => {
    const w = fakeWindows({ [`${ENV.localappdata}\\wintheme\\wintheme.py`]: "" });
    const { conflicts } = await import("../src/lib/windows/apply");
    expect((await conflicts(w.b, ENV))[0]).toMatch(/-Uninstall -KeepColors/);
    await applyAll(w.b, { ...OPTS, only: ["windows"] });
    expect(w.log.join("\n")).toMatch(/\[WARNUNG\] Das alte wintheme/);
  });
  it("Diagnose ersetzt den Benutzernamen", async () => {
    const w = fakeWindows({ [WT]: WT_TEXT });
    await applyAll(w.b, OPTS);
    const d = await diagnose(w.b);
    expect(d).not.toMatch(/jason/);
    expect(d).toContain("%USERPROFILE%");
    expect(d).toContain("✓ Windows Terminal");
  });

  it("Ausführungsrichtlinie: wirksame Stufe richtig gelesen", async () => {
    const { effectivePolicy } = await import("../src/lib/windows/apply");
    const list = (o: Record<string, string>) => ["MachinePolicy", "UserPolicy", "Process", "CurrentUser", "LocalMachine"].map((k) => `${k}=${o[k] ?? "Undefined"}`).join("\r\n");
    expect(effectivePolicy(list({}), "Restricted")).toEqual({ policy: "Restricted", scope: "Standard", managed: false });
    expect(effectivePolicy(list({ CurrentUser: "RemoteSigned", LocalMachine: "Restricted" }), "Restricted")?.policy).toBe("RemoteSigned");
    expect(effectivePolicy(list({ MachinePolicy: "AllSigned", CurrentUser: "RemoteSigned" }), "Restricted")).toMatchObject({ policy: "AllSigned", managed: true });
    expect(effectivePolicy("", "Restricted")).toBeNull();                       // nicht lesbar → keine Behauptung
  });
  it("blockierte Richtlinie → Prompt-Ergebnis ⚠ mit Lösung, Firmenvorgabe wird erkannt", async () => {
    const all = (pol: string, scope = "CurrentUser") => ["MachinePolicy", "UserPolicy", "Process", "CurrentUser", "LocalMachine"].map((k) => `${k}=${k === scope ? pol : "Undefined"}`).join("\n");
    const w = fakeWindows({}, { policy: { powershell: all("Undefined"), pwsh: all("AllSigned", "MachinePolicy") } });
    const { results } = await applyAll(w.b, { ...OPTS, only: ["ohmyposh"] });
    expect(results[0].status).toBe("warn");
    expect(results[0].message).toMatch(/Set-ExecutionPolicy -Scope CurrentUser RemoteSigned/);
    const { conflicts } = await import("../src/lib/windows/apply");
    const c = await conflicts(w.b, ENV);
    expect(c.some((x) => /PowerShell 7.*Gruppenrichtlinie/.test(x))).toBe(true);
    const ok = fakeWindows({}, { policy: { powershell: all("RemoteSigned"), pwsh: all("Undefined") } });
    expect((await applyAll(ok.b, { ...OPTS, only: ["ohmyposh"] })).results[0].status).toBe("ok");
  });
  it("Schriftliste nicht abfragbar → Schrift trotzdem gesetzt, kein falsches „nicht installiert“", async () => {
    const w = fakeWindows({ [WT]: WT_TEXT }, { fonts: [] });
    const { results } = await applyAll(w.b, { ...OPTS, only: ["terminal"] });
    expect(results[0].status).toBe("ok");
    expect((parseJsonc(w.fs.get(WT)!) as any).profiles.defaults.font.face).toBe(OPTS.fonts.mono);
  });
});
